-- Baseline for the banking schema that was created on the hosted project before migrations were kept in git.
-- Matches the live DDL (checked 2026-10-18) so a fresh project can be rebuilt; on the hosted project every
-- create is a no-op. The only real change is the card status list for the card-block executor (architecture §5.7.3).

create schema if not exists banking;
grant usage on schema banking to authenticated;

create table if not exists banking.customer_profiles (
  customer_id       bigint generated by default as identity primary key,
  auth_user_id      uuid unique references auth.users(id) on delete set null,
  demo_email        text not null unique,
  full_name         text not null,
  income_range      text not null,
  employment_status text not null check (employment_status in ('employed','self_employed','student','retired','unemployed')),
  preferred_language text not null default 'en',
  is_demo           boolean not null default true,
  created_at        timestamptz not null default now()
);

create table if not exists banking.bank_accounts (
  account_id            bigint generated by default as identity primary key,
  customer_id           bigint not null references banking.customer_profiles(customer_id) on delete cascade,
  account_type          text not null check (account_type in ('savings','current','multi_currency')),
  masked_account_number text not null check (masked_account_number ~ '^\*+[0-9]{4}$'),
  balance               numeric(14,2) not null,
  currency              char(3) not null default 'SGD',
  status                text not null default 'active' check (status in ('active','dormant','closed')),
  opened_on             date
);

create table if not exists banking.credit_card_products (
  product_id             bigint generated always as identity primary key,
  card_name              text not null unique,
  description            text,
  annual_fee             numeric(10,2),
  interest_rate_info     text,
  late_payment_fee_info  text,
  minimum_payment_info   text,
  eligibility_notes      text,
  application_procedure  text,
  is_active              boolean default true
);

create table if not exists banking.credit_cards (
  card_id             bigint generated by default as identity primary key,
  customer_id         bigint not null references banking.customer_profiles(customer_id) on delete cascade,
  card_name           text not null,
  network             text not null check (network in ('visa','mastercard')),
  last4               char(4) not null check (last4 ~ '^[0-9]{4}$'),
  credit_limit        numeric(14,2) not null,
  outstanding_balance numeric(14,2) not null default 0,
  minimum_payment_due numeric(14,2) not null default 0,
  payment_due_date    date,
  status              text not null default 'active'
);

create table if not exists banking.loan_products (
  product_id            bigint generated always as identity primary key,
  product_name          text not null unique,
  description           text,
  min_income            numeric,
  min_age               int,
  max_age               int,
  min_loan_amount       numeric,
  max_loan_amount       numeric,
  min_tenure_months     int,
  max_tenure_months     int,
  interest_rate_info    text,
  eligibility_notes     text,
  application_procedure text,
  application_channel   text,
  is_active             boolean default true
);

create table if not exists banking.loans (
  loan_id            bigint generated by default as identity primary key,
  customer_id        bigint not null references banking.customer_profiles(customer_id) on delete cascade,
  loan_type          text not null check (loan_type in ('home','car','personal','securities_backed')),
  original_amount    numeric(14,2) not null,
  outstanding_amount numeric(14,2) not null,
  monthly_repayment  numeric(14,2) not null,
  next_due_date      date,
  status             text not null default 'active' check (status in ('active','paid_off'))
);

create table if not exists banking.transactions (
  transaction_id bigint generated by default as identity primary key,
  customer_id    bigint not null references banking.customer_profiles(customer_id) on delete cascade,
  account_id     bigint references banking.bank_accounts(account_id) on delete cascade,
  card_id        bigint references banking.credit_cards(card_id) on delete cascade,
  txn_date       timestamptz not null,
  merchant       text not null,
  description    text,
  amount         numeric(14,2) not null,
  currency       char(3) not null default 'SGD',
  status         text not null check (status in ('posted','pending','failed')),
  failure_reason text,
  is_overseas    boolean not null default false,
  check (account_id is not null or card_id is not null),
  check (status = 'failed' or failure_reason is null)
);

create index if not exists bank_accounts_customer_id_idx on banking.bank_accounts (customer_id);
create index if not exists credit_cards_customer_id_idx on banking.credit_cards (customer_id);
create index if not exists loans_customer_id_idx on banking.loans (customer_id);
create index if not exists transactions_customer_id_txn_date_idx on banking.transactions (customer_id, txn_date desc);
create index if not exists transactions_account_id_idx on banking.transactions (account_id);
create index if not exists transactions_card_id_idx on banking.transactions (card_id);

-- Card states: active -> temporarily_blocked -> active | cancelled. 'blocked' and 'expired' stay for existing rows.
alter table banking.credit_cards drop constraint if exists credit_cards_status_check;
alter table banking.credit_cards add constraint credit_cards_status_check
  check (status in ('active','temporarily_blocked','cancelled','blocked','expired'));

-- The signed-in customer's id. Used by every customer policy in every schema. Security definer so it can read
-- customer_profiles without recursing through that table's own policy.
create or replace function banking.my_customer_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$ select customer_id from banking.customer_profiles where auth_user_id = auth.uid() $$;
revoke execute on function banking.my_customer_id() from public, anon;
grant execute on function banking.my_customer_id() to authenticated;

alter table banking.customer_profiles enable row level security;
alter table banking.bank_accounts enable row level security;
alter table banking.credit_card_products enable row level security;
alter table banking.credit_cards enable row level security;
alter table banking.loan_products enable row level security;
alter table banking.loans enable row level security;
alter table banking.transactions enable row level security;

-- Read-only for customers. Card state changes go through the Action Service, never a direct customer write.
drop policy if exists own_profile on banking.customer_profiles;
create policy own_profile on banking.customer_profiles for select to authenticated using (auth_user_id = (select auth.uid()));
drop policy if exists own_accounts on banking.bank_accounts;
create policy own_accounts on banking.bank_accounts for select to authenticated using (customer_id = (select banking.my_customer_id()));
drop policy if exists own_cards on banking.credit_cards;
create policy own_cards on banking.credit_cards for select to authenticated using (customer_id = (select banking.my_customer_id()));
drop policy if exists own_loans on banking.loans;
create policy own_loans on banking.loans for select to authenticated using (customer_id = (select banking.my_customer_id()));
drop policy if exists own_transactions on banking.transactions;
create policy own_transactions on banking.transactions for select to authenticated using (customer_id = (select banking.my_customer_id()));
drop policy if exists view_active_credit_card_products on banking.credit_card_products;
create policy view_active_credit_card_products on banking.credit_card_products for select to authenticated using (is_active = true);
drop policy if exists view_active_loan_products on banking.loan_products;
create policy view_active_loan_products on banking.loan_products for select to authenticated using (is_active = true);

revoke all on all tables in schema banking from anon, authenticated;
grant select on all tables in schema banking to authenticated;
