"""Manual staff CLI/customer UI preview over disposable native services, never hosted Auth or fake AI.

Run like preview_actions.py with a fresh NATIVE_PREVIEW_FILE. Metadata includes local
URLs, the handoff UUID and the path to a 0600 native staff env file. Use that env file
with scripts.staff_support while the preview runs. The staff token is generated by
the test signer for this disposable database only; no hosted role/MFA setup is tested.
The customer card begins temporarily blocked by a real confirmed synthetic command.
Start a separate Vite server, open /api/__native_preview__/session and click Start
synthetic preview. Observe real staff effects in Actions, Records and Inbox. The
normal restricted worker delivers notifications. Remove metadata to stop and clean up.
"""
import json
import os
import threading
import time
from datetime import datetime,timezone
from pathlib import Path
import jwt
import pytest
import uvicorn
from fastapi import FastAPI
from fastapi.responses import HTMLResponse
from fastapi.testclient import TestClient
from pydantic import SecretStr,StrictInt,TypeAdapter
from app.core.config import settings
from app.core.lifecycle import lifespan
from tests.data_api_support import NativeAPI,available_port
from tests.staff_cli_support import cli_gateway
from tests.test_notifications import worker_uri
from tests.test_staff_support import block,handoff,staff_token,staff_user


def test_staff_preview(local_data_api: NativeAPI,native_api_client: TestClient,worker_uri: SecretStr,monkeypatch: pytest.MonkeyPatch,tmp_path: Path) -> None:
    destination=os.environ.get('NATIVE_PREVIEW_FILE')
    if not destination:raise ValueError('Set NATIVE_PREVIEW_FILE to a fresh temporary metadata path')
    metadata=Path(destination)
    ctx,hid=handoff(local_data_api,native_api_client,'P0')
    block(native_api_client,ctx,'staff-preview-block')
    native_staff=staff_token(local_data_api,staff_user(local_data_api),'aal2',{'demobank_role':'support'})
    token=ctx.principal.jwt.get_secret_value()
    claims=jwt.decode(token,local_data_api.signing_key.public_key(),algorithms=['ES256'],audience='authenticated')
    session={'access_token':token,'refresh_token':'native-refresh-token-not-used','token_type':'bearer','expires_in':3600,
        'expires_at':TypeAdapter(StrictInt).validate_python(claims['exp']),
        'user':{'id':str(ctx.principal.user_id),'aud':'authenticated','role':'authenticated','email':'native.user@example.invalid',
            'app_metadata':{'provider':'email'},'user_metadata':{},'created_at':datetime.now(timezone.utc).isoformat()}}
    bootstrap=json.dumps({'key':'sb-127-auth-token','session':session}).replace('<','\\u003c')
    monkeypatch.setattr(settings,'run_worker_in_api',True)
    monkeypatch.setattr(settings,'worker_database_url',worker_uri)
    preview=FastAPI(lifespan=lifespan)

    @preview.get('/__native_preview__/session',response_class=HTMLResponse)
    def entry() -> str:
        return '<!doctype html><html lang="en"><meta charset="utf-8"><title>Native staff outcome preview</title><main><h1>Local synthetic staff outcome preview</h1><p>Use the native staff CLI, then review its actual receipts and card state in the normal customer app. This does not test hosted password login, hosted MFA or AI accuracy.</p><button id="start-preview-session" aria-label="Start synthetic preview">Start synthetic preview</button></main><script>const fixture='+bootstrap+''';
document.getElementById('start-preview-session').addEventListener('click',()=>{
  localStorage.removeItem('demobank.active.'+fixture.session.user.id);
  localStorage.setItem(fixture.key,JSON.stringify(fixture.session));location.assign('/');
});</script></html>'''

    preview.mount('/',native_api_client.app)
    port=available_port()
    server=uvicorn.Server(uvicorn.Config(preview,host='127.0.0.1',port=port,log_level='warning',access_log=False))
    thread=threading.Thread(target=server.run,name='native-staff-preview',daemon=True)
    with cli_gateway(local_data_api) as staff_url:
        env_file=tmp_path/'.env.staff'
        with os.fdopen(os.open(env_file,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600),'w') as output:
            output.write('SUPABASE_URL='+staff_url+'\nSUPABASE_ANON_KEY=sb_publishable_native_preview_public_key\nSTAFF_ACCESS_TOKEN='+native_staff+'\n')
        thread.start()
        try:
            deadline=time.monotonic()+10
            while not server.started:
                if not thread.is_alive():raise RuntimeError('Native staff outcome preview stopped during startup')
                if time.monotonic()>deadline:raise TimeoutError('Native staff outcome preview did not start within ten seconds')
                time.sleep(0.05)
            with metadata.open('x') as output:json.dump({'backend_port':port,'data_api_url':local_data_api.url,
                'staff_env_file':str(env_file),'handoff_id':str(hid)},output)
            print('Native staff preview ready:',str(metadata),flush=True)
            deadline=time.monotonic()+900
            while metadata.exists():
                if not thread.is_alive():raise RuntimeError('Native staff outcome preview stopped unexpectedly')
                if time.monotonic()>deadline:raise TimeoutError('Native staff preview exceeded fifteen minutes; remove metadata to stop it')
                time.sleep(0.1)
        finally:
            server.should_exit=True
            thread.join(timeout=10)
            env_file.unlink()
            if thread.is_alive():raise TimeoutError('Native staff outcome preview did not stop within ten seconds')
